/* tests/sha256-parity.js — run with node: verifies assets/js/sha256.js
   produces identical hashes to PHP Pack::chainEvents. Node version of the
   harness: loads sha256.js in a fake window, canonicalizes like Pack::canon,
   compares against fixtures generated by PHP (tests/sha256-fixtures.json). */
const fs = require('fs');
global.window = {};
eval(fs.readFileSync(__dirname + '/../assets/js/sha256.js', 'utf8'));
const c = global.window.popCrypto;

let fails = 0;
function check(name, cond) {
  console.log((cond ? 'ok  ' : 'FAIL ') + name);
  if (!cond) fails++;
}

const fixtures = JSON.parse(fs.readFileSync(__dirname + '/sha256-fixtures.json', 'utf8'));
check('fixture count', fixtures.length >= 10);
for (const f of fixtures) {
  const js = c.sha256Hex(f.input);
  if (js !== f.php) { check('hash parity: ' + f.name, false); }
}
check('sha256 parity on ' + fixtures.length + ' fixtures', true);

// canon parity
const canonCases = [
  [{ b: 2, a: 1, n: { z: 1, y: [{ q: 3, p: 4 }] } }, '{"a":1,"b":2,"n":{"y":[{"p":4,"q":3}],"z":1}}'],
  [{ text: 'héllo / "quoted" ✓ ✍' }, '{"text":"héllo / \\"quoted\\" ✓ ✍"}'],
];
for (const [obj, expected] of canonCases) {
  check('canon parity: ' + expected.slice(0, 30), c.canon(obj) === expected);
}

// long-input edge (multi-block sha256, 1MB of 'a')
let big = 'a'.repeat(1000000);
check('sha256 1MB input matches PHP digest', c.sha256Hex(big) === fixtures.find(f => f.name === '1MB-a').php);

console.log(fails === 0 ? 'ALL PASSED' : 'FAILURES: ' + fails);
process.exit(fails === 0 ? 0 : 1);
