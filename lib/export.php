<?php
/**
 * lib/export.php — render a pack as a self-contained HTML file that:
 *   - works offline (no server, no external resources),
 *   - re-verifies its own chain in the browser (inlined sha256.js),
 *   - replays the writing session in the DOM (replay UI from assets,
 *     inlined; identical verify+replay logic as the site pages).
 *
 * The pack JSON is embedded once inside a <script type="application/json">
 * block (hex-escaped so it can never break out into markup).
 */

declare(strict_types=1);

function pop_export_html(array $pack, array $verdict, string $siteUrl = ''): string
{
    $packJson = json_encode($pack, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    // Embed as base64 of the JSON to be injection-proof and encoding-safe.
    $packB64 = base64_encode($packJson);
    $sha = file_get_contents(POP_ROOT . '/assets/js/sha256.js');
    $replay = file_get_contents(POP_ROOT . '/assets/js/replay.js');
    $verdictJson = json_encode($verdict, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);

    $title = e($pack['title'] !== '' ? $pack['title'] : 'Untitled proof pack');
    $author = e($pack['author']);
    $id = e($pack['id']);
    $head = e($pack['chain_head']);
    $created = e($pack['created_at']);
    $valid = $verdict['valid'] ? 'VALID' : 'TAMPERED';
    $validClass = $verdict['valid'] ? 'valid' : 'bad';

    return <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>ProofOfPen pack {$id} — {$title}</title>
<style>
:root{--paper:#FAFAF7;--ink:#1A1A18;--verdigris:#2E5E4E;--terra:#B4552D;--rule:#E8E6DF}
*{box-sizing:border-box}
body{margin:0;background:var(--paper);color:var(--ink);font:15px/1.6 system-ui,sans-serif}
main{max-width:760px;margin:0 auto;padding:24px 20px 80px}
h1{font-size:1.3rem}
.banner{padding:14px 18px;border-radius:8px;font-weight:600;margin:16px 0}
.banner.valid{background:var(--verdigris);color:#fff}
.banner.bad{background:var(--terra);color:#fff}
.meta{font-family:ui-monospace,monospace;font-size:13px;color:#555;word-break:break-all}
.card{background:#fff;border:1px solid var(--rule);border-radius:10px;padding:16px 18px;margin:14px 0}
button{font:inherit;background:var(--verdigris);color:#fff;border:0;border-radius:8px;padding:10px 16px;cursor:pointer}
button.sec{background:transparent;color:var(--verdigris);border:1px solid var(--verdigris)}
#replayText{font:17px/1.7 Georgia,'Times New Roman',serif;white-space:pre-wrap;min-height:120px;border:1px solid var(--rule);border-radius:8px;padding:14px;background:#fff}
input[type=range]{width:100%}
.warn{color:var(--terra)}
.small{font-size:13px;color:#666}
</style>
</head>
<body>
<main>
<h1>ProofOfPen — proof pack {$id}</h1>
<p class="small">A process receipt of a live writing session. Receipts, not detection:
this file proves the recorded session is intact, not that a human wrote it.</p>

<div class="banner {$validClass}">Chain check: {$valid}</div>
<div id="verdictDetail" class="meta"></div>

<div class="card">
<div><strong>{$title}</strong></div>
<div class="small">by {$author} · created {$created} · {$created}</div>
<div class="meta">pack id: {$id}<br>chain head: {$head}</div>
</div>

<div class="card">
<h2 style="font-size:1rem">Replay</h2>
<div><button id="play">Play</button> <button class="sec" id="speed">Speed 1×</button></div>
<input type="range" id="scrub" min="0" max="1000" value="0">
<div id="replayText"></div>
<p class="small" id="replayNote"></p>
</div>

<div class="card">
<h2 style="font-size:1rem">Final text</h2>
<div id="finalText" style="white-space:pre-wrap;font:17px/1.7 Georgia,serif"></div>
</div>

<p class="small">Verify online: {$siteUrl}verify?id={$id} · Generated by ProofOfPen (MVP Lab).</p>
</main>
<script type="application/json" id="packB64">{$packB64}</script>
<script>{$sha}</script>
<script>{$replay}</script>
<script>
var pack = JSON.parse(popB64Decode(document.getElementById('packB64').textContent.trim()));
var verdict = {$verdictJson};
document.getElementById('finalText').textContent = pack.final_text;
var vd = document.getElementById('verdictDetail');
vd.textContent = verdict.valid
  ? 'All ' + verdict.stats.events + ' events re-hash to the recorded chain head. '
    + verdict.stats.typed_chars + ' typed chars, ' + verdict.stats.pasted_chars + ' pasted chars, '
    + verdict.stats.fast_bursts + ' unusually fast bursts.'
  : 'Integrity failure: ' + verdict.reason
    + (verdict.first_bad_index !== null ? ' (event #' + verdict.first_bad_index + ')' : '');
// Offline re-check with the inlined hasher (independent from the PHP verdict).
var rec = popVerify(pack);
var b = document.querySelector('.banner');
if (rec.valid !== verdict.valid) {
  b.textContent = 'Chain check: RE-CHECK DISAGREES — ' + (rec.valid ? 'VALID' : 'TAMPERED');
}
popReplay(pack, {
  text: document.getElementById('replayText'),
  play: document.getElementById('play'),
  speed: document.getElementById('speed'),
  scrub: document.getElementById('scrub'),
  note: document.getElementById('replayNote')
});
function popB64Decode(s){
  var bin = atob(s), bytes = new Uint8Array(bin.length);
  for (var i=0;i<bin.length;i++) bytes[i]=bin.charCodeAt(i);
  return new TextDecoder().decode(bytes);
}
</script>
</body>
</html>
HTML;
}
